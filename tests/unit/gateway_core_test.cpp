#include "config_store.hpp"
#include "pairing.hpp"
#include "status_model.hpp"

#include "test_util.hpp"

#include <fstream>
#include <string>

namespace {

using orca::ui::AdminStatus;
using orca::ui::ChipLevel;
using orca::ui::ConfigSnapshot;
using orca::ui::ConfigStore;
using orca::ui::ConfigUpdate;
using orca::ui::VerdictLevel;
using orca::ui::normalizeHubUrl;

const char* kPairCode =
    "eyJ2IjoxLCJlbmRwb2ludCI6IndzOi8vMTkyLjE2OC4xLjU6OTMyMSIsImRldmljZVRva2VuIjoidG9rLWFiYy0xMjMiLCJwdWJsaWNLZXlCNjQiOiJhR1ZzYkc4PSIsInNjb3BlIjoibW9iaWxlIiwicGFpcmVkRGV2aWNlSWQiOiJkZXYtMSJ9";

template <typename Fn>
bool throwsWith(Fn fn, const std::string& needle) {
    try {
        fn();
    } catch (const std::exception& error) {
        return std::string(error.what()).find(needle) != std::string::npos;
    }
    return false;
}

void writeText(const std::filesystem::path& path, const std::string& text) {
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out << text;
}

}  // namespace

int main() {
    // ---- hub URL normalization (config.ts:154-166) ------------------------
    test::check(normalizeHubUrl("  wss://example.com ") == "wss://example.com/gateway",
                "normalizeHubUrl appends /gateway and trims");
    test::check(normalizeHubUrl("ws://example.com/gateway/") == "ws://example.com/gateway",
                "normalizeHubUrl keeps an existing /gateway and drops trailing slash");
    test::check(normalizeHubUrl("wss://example.com/base") == "wss://example.com/base/gateway",
                "normalizeHubUrl appends /gateway to a custom path");
    test::check(throwsWith([] { (void)normalizeHubUrl("https://example.com"); },
                           "ws:// 或 wss://"),
                "normalizeHubUrl rejects http(s) schemes");
    test::check(throwsWith([] { (void)normalizeHubUrl("not-a-url"); }, "无法解析"),
                "normalizeHubUrl rejects malformed input");

    // ---- pairing code (config.ts:178-218), vectors generated by Node ------
    const auto offer = orca::ui::decodePairingCode(std::string("orca://pair?code=") + kPairCode);
    test::check(offer.version == 1, "pairing deep link: version");
    test::check(offer.deviceToken == "tok-abc-123", "pairing deep link: deviceToken");
    test::check(offer.publicKeyB64 == "aGVsbG8=", "pairing deep link: publicKeyB64");
    test::check(offer.scope == "mobile", "pairing deep link: scope");
    test::check(offer.pairedDeviceId == "dev-1", "pairing deep link: pairedDeviceId");
    test::check(offer.endpoint == "ws://192.168.1.5:9321", "pairing deep link: endpoint");

    const auto bare = orca::ui::decodePairingCode(kPairCode);
    test::check(bare.deviceToken == offer.deviceToken, "bare base64url code is accepted");
    const auto ampersand = orca::ui::decodePairingCode(std::string("orca://pair?x=1&code=") + kPairCode);
    test::check(ampersand.deviceToken == offer.deviceToken, "&code= separator is accepted");
    const auto prefixed = orca::ui::decodePairingCode(std::string("code=") + kPairCode);
    test::check(prefixed.deviceToken == offer.deviceToken, "code= prefix is accepted");

    test::check(orca::ui::loopbackEndpoint(offer.endpoint) == "ws://127.0.0.1:9321",
                "loopbackEndpoint forces 127.0.0.1 and keeps the port");
    test::check(orca::ui::loopbackEndpoint("ws://192.168.1.5:9321/orca") == "ws://127.0.0.1:9321/orca",
                "loopbackEndpoint keeps a non-root path");
    test::check(throwsWith([] { (void)orca::ui::loopbackEndpoint("garbage"); }, "无法解析"),
                "loopbackEndpoint rejects a malformed endpoint");

    test::check(throwsWith([] { (void)orca::ui::decodePairingCode("   "); }, "配对码为空"),
                "empty pairing code is rejected");
    test::check(throwsWith([] { (void)orca::ui::decodePairingCode("orca://pair?code=!!!"); },
                           "没有可解码"),
                "pairing code without base64 content is rejected");
    test::check(throwsWith([] {
        (void)orca::ui::decodePairingCode(
            "orca://pair?code=eyJlbmRwb2ludCI6IndzOi8vMTkyLjE2OC4xLjU6OTMyMSIsInB1YmxpY0tleUI2NCI6ImFHVnNiRzg9In0");
    }, "deviceToken"), "pairing code without deviceToken is rejected");
    test::check(throwsWith([] {
        (void)orca::ui::decodePairingCode(
            "orca://pair?code=eyJ2IjoxLCJlbmRwb2ludCI6IndzOi8vMTkyLjE2OC4xLjU6OTMyMSIsImRldmljZVRva2VuIjoidG9rLWFiYy0xMjMiLCJwdWJsaWNLZXlCNjQiOiJhR1ZzYkc4PSIsInNjb3BlIjoiZGVza3RvcCIsInBhaXJlZERldmljZUlkIjoiZGV2LTEifQ");
    }, "需要 mobile"), "non-mobile scope is rejected");

    // ---- ConfigStore: merge, atomics, BOM, unknown keys -------------------
    const std::filesystem::path dir =
        std::filesystem::temp_directory_path() / "orca-gateway-core-test";
    std::error_code cleanup;
    std::filesystem::remove_all(dir, cleanup);
    std::filesystem::create_directories(dir, cleanup);
    const std::filesystem::path configPath = dir / "gateway.json";

    ConfigStore store(configPath);
    test::check(!store.read().exists, "missing config file is reported, not fatal");
    test::check(ConfigUpdate{}.empty(), "empty ConfigUpdate is detected");

    writeText(configPath, "{\"serverUrl\":\"ws://old\",\"gatewayKey\":\"k0\",\"extra\":{\"keep\":true}}");
    ConfigUpdate keyOnly;
    keyOnly.gatewayKey = "k1";
    (void)store.apply(keyOnly);
    ConfigSnapshot snapshot = store.read();
    test::check(snapshot.exists && snapshot.error.empty(), "config file reads back cleanly");
    test::check(snapshot.serverUrl == "ws://old", "apply() leaves untouched fields alone");
    test::check(snapshot.gatewayKey == "k1", "apply() updates gatewayKey");
    test::check(snapshot.raw.find("\"keep\": true") != std::string::npos,
                "apply() preserves unknown keys");

    ConfigUpdate urlOnly;
    urlOnly.serverUrl = "wss://new.example.com/";
    (void)store.apply(urlOnly);
    test::check(store.read().serverUrl == "wss://new.example.com/gateway",
                "apply() normalizes serverUrl before persisting");

    ConfigUpdate pairingUpdate;
    pairingUpdate.orca = {"ws://127.0.0.1:9321", "tok-abc-123", "aGVsbG8="};
    (void)store.apply(pairingUpdate);
    test::check(store.read().orca.deviceToken == "tok-abc-123",
                "apply() persists the orca pairing block");
    test::check(!std::filesystem::exists(std::filesystem::path(configPath.string() + ".tmp")),
                "atomic write leaves no .tmp behind");

    writeText(configPath, "\xEF\xBB\xBF{\"gatewayKey\":\"bom\"}");
    test::check(store.read().gatewayKey == "bom" && store.read().error.empty(),
                "UTF-8 BOM from PowerShell 5.1 is stripped before parsing");

    writeText(configPath, "{ broken json");
    test::check(throwsWith([&] { (void)store.apply(keyOnly); }, "拒绝覆盖"),
                "apply() refuses to overwrite an unparsable config");
    std::filesystem::remove_all(dir, cleanup);

    // ---- four-quadrant verdict + pairing chips ----------------------------
    AdminStatus status;
    test::check(orca::ui::evaluate(status).level == VerdictLevel::kError,
                "verdict: both links down -> error");
    status.hubConnected = true;
    test::check(orca::ui::evaluate(status).level == VerdictLevel::kWarn,
                "verdict: hub up / Orca down -> warn");
    status.hubConnected = false;
    status.orcaState = "connected";
    test::check(orca::ui::evaluate(status).level == VerdictLevel::kWarn,
                "verdict: hub down / Orca up -> warn");
    status.hubConnected = true;
    test::check(orca::ui::evaluate(status).level == VerdictLevel::kOk,
                "verdict: both links up -> ok");

    status = AdminStatus{};
    test::check(orca::ui::pairingState(status).chipLevel == ChipLevel::kOff,
                "pairing chip: unpaired");
    status.pairedVia = "local-orca";
    test::check(orca::ui::pairingState(status).chipLevel == ChipLevel::kWarn,
                "pairing chip: local material, waiting");
    status.orcaMachineName = "DESKTOP-1";
    test::check(orca::ui::orcaIdentity(status) == "DESKTOP-1",
                "orcaIdentity uses the machine name alone");
    status.orcaAppVersion = "1.2.3";
    test::check(orca::ui::orcaIdentity(status) == "Orca 1.2.3 · DESKTOP-1",
                "orcaIdentity joins version and machine");

    return test::finish("gateway core tests");
}
